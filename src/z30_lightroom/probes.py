"""Probe LUTs that reveal where and in which encoding Camera Raw applies a profile LUT.

Each probe is a simple known function. If Camera Raw applies the LUT to the
ProPhoto-encoded values at the end of its pipeline, then a probe export equals
the probe function applied to the identity export. `characterize` tests that
hypothesis and two alternatives (LUT applied in sRGB or Adobe RGB encoding)
and reports which one, if any, predicts the real exports.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Callable

import numpy as np

from portra160_lab.color import delta_e_2000
from .colorimetry import PROPHOTO_TO_XYZ, prophoto_decode, prophoto_encode, xyz_to_lab
from .cube import identity_lut, write_cube

PROBES: dict[str, Callable[[np.ndarray], np.ndarray]] = {
    "identity": lambda x: x,
    "red_gain_085": lambda x: x * np.array([0.85, 1.0, 1.0]),
    "power_125": lambda x: np.clip(x, 0, 1) ** 1.25,
    "rotate_rgb_gbr": lambda x: x[..., [1, 2, 0]],
}

# ICC-style D50-adapted RGB -> XYZ matrices for the alternative hypotheses.
SPACES = {
    "prophoto": (PROPHOTO_TO_XYZ, 1.8),
    "srgb": (np.array([[0.4360747, 0.3850649, 0.1430804],
                       [0.2225045, 0.7168786, 0.0606169],
                       [0.0139322, 0.0971045, 0.7141733]]), None),
    "adobergb": (np.array([[0.6097559, 0.2052401, 0.1492240],
                           [0.3111242, 0.6256560, 0.0632197],
                           [0.0194811, 0.0608902, 0.7448387]]), 563 / 256),
}


def _decode(enc, gamma):
    enc = np.clip(enc, 0, 1)
    if gamma is None:  # sRGB piecewise curve
        return np.where(enc <= 0.04045, enc / 12.92, ((enc + 0.055) / 1.055) ** 2.4)
    return enc ** gamma


def _encode(lin, gamma):
    lin = np.clip(lin, 0, 1)
    if gamma is None:
        return np.where(lin <= 0.0031308, 12.92 * lin, 1.055 * lin ** (1 / 2.4) - 0.055)
    return lin ** (1 / gamma)


def predict(identity_enc: np.ndarray, probe: str, space: str) -> np.ndarray:
    """Predicted ProPhoto-encoded export if the probe LUT is applied in `space` encoding."""
    m, gamma = SPACES[space]
    xyz = prophoto_decode(identity_enc) @ PROPHOTO_TO_XYZ.T
    in_space = _encode(xyz @ np.linalg.inv(m).T, gamma)
    out_xyz = _decode(PROBES[probe](in_space), gamma) @ m.T
    return prophoto_encode(out_xyz @ np.linalg.inv(PROPHOTO_TO_XYZ).T)


def characterize(identity_enc: np.ndarray, probe_enc: np.ndarray, probe: str) -> dict:
    """ΔE00 between each hypothesis' prediction and the actual probe export (block means)."""
    actual = xyz_to_lab(prophoto_decode(probe_enc) @ PROPHOTO_TO_XYZ.T)
    result = {}
    for space in SPACES:
        pred = xyz_to_lab(prophoto_decode(predict(identity_enc, probe, space)) @ PROPHOTO_TO_XYZ.T)
        de = delta_e_2000(actual, pred)
        result[space] = {"mean": float(de.mean()), "p95": float(np.percentile(de, 95)), "max": float(de.max())}
    best = min(result, key=lambda s: result[s]["mean"])
    result["best_hypothesis"] = best
    result["hypothesis_holds"] = bool(result[best]["mean"] <= 1.0 and result[best]["p95"] <= 2.0)
    return result


def write_probe_kit(out_dir: Path, n: int = 33) -> dict:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    grid = identity_lut(n)
    files = {}
    for name, fn in PROBES.items():
        path = out_dir / f"z30_probe_{name}.cube"
        write_cube(path, fn(grid), title=f"Z30 probe {name}",
                   comments=["Diagnostic probe LUT, not a film look.",
                             "Generated by z30_lightroom.probes; GPL-3.0-only."])
        files[name] = path.name
    manifest = {"format": "z30-probe-kit-v1", "lut_size": n, "files": files,
                "domain": "Load each in Camera Raw's Create Profile dialog with table space ProPhoto RGB."}
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest
